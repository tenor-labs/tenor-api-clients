"""Generates the client from ../../openapi/trading-api.json:

- src/tenor_api_client/_generated: openapi-python-client output
- src/tenor_api_client/client.py: Tenor and AsyncTenor, one method per operation, read from the
  generated endpoint modules
"""

from __future__ import annotations

import ast
import shutil
import subprocess
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "src" / "tenor_api_client"
GENERATED = PACKAGE / "_generated"
SPEC = ROOT.parent.parent / "openapi" / "trading-api.json"

# Names the facade annotations use that aren't models.
NOT_MODELS = {"Any", "Unset", "UNSET", "str", "int", "float", "bool", "dict", "list", "None"}
# Return members that never reach the caller: errors raise, and a 304 only answers If-None-Match.
NOT_RETURNED = {"Any", "ErrorResponse"}


def run_generator() -> None:
    shutil.rmtree(GENERATED, ignore_errors=True)
    subprocess.run(
        [
            "openapi-python-client",
            "generate",
            "--path",
            str(SPEC),
            "--meta",
            "none",
            "--output-path",
            str(GENERATED),
            "--config",
            str(ROOT / "openapi-python-client.yaml"),
            "--custom-template-path",
            str(ROOT / "templates"),
        ],
        check=True,
    )


def names(node: ast.AST) -> set[str]:
    return {n.id for n in ast.walk(node) if isinstance(n, ast.Name)}


def union_members(node: ast.expr) -> list[ast.expr]:
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.BitOr):
        return union_members(node.left) + union_members(node.right)
    return [node]


class Method:
    def __init__(self, tag: str, path: Path) -> None:
        self.name = path.stem
        self.module = f"_generated.api.{tag}.{self.name}"
        tree = ast.parse(path.read_text())
        fn = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "sync_detailed")
        self.imports: set[str] = set()
        self.params: list[str] = []
        self.args: list[str] = []
        positional = fn.args.args
        if positional:
            for arg in positional:
                self.params.append(self.param(arg, None))
        kwonly = [
            (a, d) for a, d in zip(fn.args.kwonlyargs, fn.args.kw_defaults, strict=True) if a.arg != "client"
        ]
        if kwonly:
            self.params.append("*")
            for arg, default in kwonly:
                self.params.append(self.param(arg, default))
        assert isinstance(fn.returns, ast.Subscript), f"{self.name}: unexpected return annotation"
        returned = [m for m in union_members(fn.returns.slice) if ast.unparse(m) not in NOT_RETURNED]
        assert returned, f"{self.name}: no success type"
        self.returns = " | ".join(ast.unparse(m) for m in returned)
        for m in returned:
            self.imports |= names(m)
        doc = ast.get_docstring(fn) or ""
        self.doc = doc.split("\n\nRaises:")[0].rstrip()

    def param(self, arg: ast.arg, default: ast.expr | None) -> str:
        assert arg.annotation is not None
        annotation = ast.unparse(arg.annotation)
        self.imports |= names(arg.annotation)
        if arg.arg == "body":
            # Bodies are one model; accept its wire-format dict as well.
            self.args.append(f"body=as_model({annotation}, body)")
            annotation = f"{annotation} | Mapping[str, Any]"
        else:
            self.args.append(f"{arg.arg}={arg.arg}")
        return f"{arg.arg}: {annotation}" + (f" = {ast.unparse(default)}" if default is not None else "")

    def render(self, is_async: bool) -> str:
        params = ", ".join(["self", *self.params])
        endpoint = f"_{self.name}.{'asyncio' if is_async else 'sync'}_detailed"
        call = f"self._call({endpoint}, {', '.join(self.args)})"
        doc = textwrap.indent(f'"""{self.doc}\n"""', " " * 8).lstrip()
        return (
            f"    {'async ' if is_async else ''}def {self.name}({params}) -> {self.returns}:\n"
            f"        {doc}\n"
            f"        return {'await ' if is_async else ''}{call}\n"
        )


def write_facade() -> None:
    methods = sorted(
        (
            Method(tag.name, path)
            for tag in (GENERATED / "api").iterdir()
            if tag.is_dir()
            for path in tag.glob("*.py")
            if path.name != "__init__.py"
        ),
        key=lambda m: m.name,
    )
    models = sorted(set().union(*(m.imports for m in methods)) - NOT_MODELS)
    lines = [
        "# Generated by scripts/generate.py from openapi/trading-api.json. Do not edit.",
        "from __future__ import annotations",
        "",
        "from collections.abc import Mapping",
        "from typing import Any",
        "",
        "from ._base import AsyncBaseClient, BaseClient, as_model",
        *(f"from .{m.module.rsplit('.', 1)[0]} import {m.name} as _{m.name}" for m in methods),
        "from ._generated.models import (",
        *(f"    {name}," for name in models),
        ")",
        "from ._generated.types import UNSET, Unset",
        "",
        "",
        "class Tenor(BaseClient):",
        '    """Client for the Tenor Trading API. Every method returns the response model, with ``data``',
        '    and ``meta``, and raises ``TenorApiError`` on an error response."""',
        "",
        "\n".join(m.render(False) for m in methods),
        "",
        "class AsyncTenor(AsyncBaseClient):",
        '    """Async client for the Tenor Trading API. Same methods as ``Tenor``."""',
        "",
        "\n".join(m.render(True) for m in methods),
    ]
    (PACKAGE / "client.py").write_text("\n".join(lines))
    print(f"generated {len(methods)} operations")


if __name__ == "__main__":
    run_generator()
    write_facade()
    subprocess.run(["ruff", "check", "--fix", "--quiet", str(PACKAGE / "client.py")], check=True)
    subprocess.run(["ruff", "format", "--quiet", str(PACKAGE / "client.py")], check=True)
